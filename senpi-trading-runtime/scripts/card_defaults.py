"""The `defaults` field on every catalog card: how each wallet of a template is set out of the box.

GENERATED by gen_catalog.py, never authored. Every value is read from the package's own files: each
instance's runtime.yaml, and the scanner's own table where a scanner keeps one in code. Cards used to
state size in prose or not at all (17 Nov 2026: 99 of 145 never said how big a position is), and an
agent sized Mustang S&P at "~4% of account" where the package opens 30% of free margin at 3x.

SIZE, as the runtime applies it. A signal's `marginPct` is a percent of the wallet's FREE margin at
the open (withdrawable, less margin already committed); a signal without one is sized at
`strategy.margin_pct`. So a case `of: "free margin"` opens the first position on a fresh wallet at
that percent of the wallet, and each later one at that percent of what is still free. A few scanners
convert a share of the ACCOUNT into that percent (kudu, yak, squirrel, chipmunk): `of: "account"`,
and every position is the same size. Size that differs by signal is listed case by case (a leg, a
tier, a market), never flattened into one number. Size the config cannot state (set per signal from
volatility, say) is `margin_pct: null` with `set_by`, so the card says it does not state one.

HOW EACH ENGINE SIZES lives in SIZING below, keyed by package id. A package not listed there is
read the default way: the scanner's `marginPct` (else `strategy.margin_pct`) at its `leverage` (else
`strategy.default_leverage`) on every signal. That is right only for a scanner that emits its config
unchanged, so `test_card_defaults.py` fails on a package whose inputs carry a sizing key the default
reading ignores; add the package to SIZING, reading its scanner first. A scanner that changes the
size in code with no such key cannot be caught by a test: check it when the template is reviewed.
"""
