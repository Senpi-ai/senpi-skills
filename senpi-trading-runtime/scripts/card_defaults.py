import ast
import os

FREE = "free margin"
ACCOUNT = "account"

# Scanner input keys that change the size or leverage of a signal away from one flat value. A package
# whose inputs carry one of these must be described in SIZING (the default reading would flatten it).
SIZING_KEYS = (
    "marginPctTiers", "leverageTiers", "sizingTiers", "sizingWeights", "maxMarginPct", "marginPctMax",
    "minMarginPct", "marginPctCap", "leverageByAsset", "washoutMarginPct", "washoutLeverage",
    "basketLeverage", "leverageMin", "minLeverage", "stdLeverage", "baseRiskPct", "hedgeRiskPct",
    "convictionMarginScale", "qualityMarginScale", "qualityTiers", "riskOffSizeScale", "broadSizeScale",
    "mixedSizeScale", "minSizeScale", "maxSizeScale", "highMarginPct", "addMarginPct",
    "leverageTierBase", "leverageTierMid", "leverageTierHigh", "leverageTrend", "leverageRange",
    "marginPctBaseTrend", "marginPctBaseRange", "maxWeightPct", "minAllocationPct",
    "baseAllocationPct", "maxAllocationPct", "weekendLeverageCap", "riskOffMultiplier",
)
_MARGIN_KEYS = ("marginPct", "marginPctBase", "margin_pct")
_LEVERAGE_KEYS = ("leverage", "leverageDefault", "defaultLeverage", "baseLeverage")


def _num(v):
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return int(f) if f.is_integer() else round(f, 4)


def _scanner_inputs(rt):
    """The external scanner's inputs (the one that emits entries; a second one only closes)."""
    for sc in rt.get("scanners") or []:
        if isinstance(sc, dict) and sc.get("type") == "external_scanner" and isinstance(sc.get("inputs"), dict):
            return sc["inputs"]
    return {}


def _pct(v):
    """A sizing percent in (1, 100]; None for anything else (a pasted fraction or a risk weight is
    not a slot size: min_budget.py draws the same line)."""
    v = _num(v)
    return v if v is not None and 1 < v <= 100 else None


def flat_margin(rt):
    inp = _scanner_inputs(rt)
    for k in _MARGIN_KEYS:
        if _pct(inp.get(k)) is not None:
            return _pct(inp[k])
    return _pct((rt.get("strategy") or {}).get("margin_pct"))


def flat_leverage(rt):
    inp = _scanner_inputs(rt)
    lev = next((_num(inp[k]) for k in _LEVERAGE_KEYS if _num(inp.get(k))), None)
    if lev is None:
        lev = _num((rt.get("strategy") or {}).get("default_leverage"))
    return lev


def case(when, margin_pct, leverage, of=FREE, **extra):
    out = {"when": when, "margin_pct": margin_pct, "of": of, "leverage": leverage}
    out.update(extra)
    return out


def code_constant(pkg_dir, inst_dir, filename, name):
    """A literal table a scanner keeps in code (`TIERS = [...]`), read with ast.literal_eval, never
    imported: the card follows the code without running it."""
    path = os.path.join(pkg_dir, inst_dir, "scanners", filename)
    tree = ast.parse(open(path, encoding="utf-8").read())
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else (
            [node.target] if isinstance(node, ast.AnnAssign) else [])
        if any(isinstance(t, ast.Name) and t.id == name for t in targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{path}: no module-level {name}")


def flat(of=FREE, lev_keys=None, lev_cap_key=None):
    """One size for every signal: the scanner emits its config unchanged (FREE), or converts that share
    of the account into the percent it emits (ACCOUNT). `lev_keys` / `lev_cap_key` where the one
    leverage comes from other keys (jackal: stdLeverage capped at maxLeverage)."""
    def size(rt, ctx):
        i = ctx["inputs"]
        lev = next((_num(i[k]) for k in lev_keys or () if _num(i.get(k))), None) or flat_leverage(rt)
        return [case("every entry", flat_margin(rt), _cap(lev, _num(i.get(lev_cap_key))), of)]
    return size


default_size = flat()


def _bare(asset):
    return str(asset).split(":")[-1].upper()


def _span(lo, hi):
    """A value that differs by signal: [low, high], or the one value when both ends agree."""
    lo, hi = _num(lo), _num(hi)
    return lo if lo == hi else [lo, hi]


def _cap(v, cap):
    return v if cap is None or v is None else min(v, cap)


def _merge(spans, label):
    """[low, top, margin, leverage] score spans, highest first, as cases; neighbours that size alike
    are one case. A span with no low end is everything under `top`."""
    merged = []
    for sp in spans:
        if merged and merged[-1][2:] == sp[2:]:
            merged[-1][0] = sp[0]
        else:
            merged.append(list(sp))
    return [case(f"{label} {lo}+" if top is None else f"{label} under {top}" if lo is None
                 else f"{label} {lo} to under {top}", m, lev) for lo, top, m, lev in merged]


def by_market(markets, lev_of, margin_pct, of=FREE):
    """A per-market leverage table as one case per leverage, naming its markets."""
    groups = {}
    for m in markets or []:
        groups.setdefault(lev_of(m), []).append(m)
    return [case(", ".join(ms), margin_pct, lev, of, markets=ms) for lev, ms in groups.items()]


def per_market(of):
    """marginPct on every signal, at the market's own leverage: scoring.leverage_for in gannet, ocelot,
    kinkajou and yak reads leverageByAsset on the bare ticker, else leverageDefault, a whole number
    >= 1 capped at leverageMax. Yak converts marginPct of the ACCOUNT (scan.py: clip = account_value *
    margin_pct / 100); the others emit marginPct of free margin as configured."""
    def size(rt, ctx):
        i = ctx["inputs"]
        table = {_bare(k): v for k, v in (i.get("leverageByAsset") or {}).items()}

        def lev(m):
            raw = _num(table.get(_bare(m), i.get("leverageDefault", 1)))
            return int(max(1, min(round(raw), _num(i.get("leverageMax", raw)))))
        return by_market(universe(rt), lev, _pct(i.get("marginPct")), of)
    return size


def bands(scale_keys=(), floor=None, skip=()):
    """Conviction bands: marginPctTiers / leverageTiers keyed by band (apex / good / base), one case per
    band, leverage capped at maxLeverage, margin at maxMarginPct. A size scale the scanner applies on
    top (scale_keys: a posture's mixedSizeScale, a self-tuned min/maxSizeScale) makes each band's margin
    a range, never under `floor`, the scanner's smallest percent. `skip`: a band no score can reach."""
    def size(rt, ctx):
        i = ctx["inputs"]
        mt, lt = i.get("marginPctTiers") or {}, i.get("leverageTiers") or {}
        scales = [s for s in (_num(i.get(k)) for k in scale_keys) if s is not None] + [1]
        out = []
        for band in [b for b in (mt or lt) if b not in skip]:
            m = _num(mt.get(band)) if mt else flat_margin(rt)
            lo, hi = (max(_cap(round(m * x, 2), _num(i.get("maxMarginPct"))), floor or 0)
                      for x in (min(scales), max(scales)))
            lev = _cap(_num(lt.get(band)), _num(i.get("maxLeverage"))) if lt else flat_leverage(rt)
            out.append(case(f"{band}-band signals", _span(lo, hi), lev))
        return out
    return size


def _table_rows(table):
    """Score rows as [min_score, leverage, margin percent or None]: lists [score, lev(, margin|label)] or
    dicts {min_score|minScore, leverage, marginPct}, a margin <= 1 read as the fraction the scanner
    multiplies by 100 (dire)."""
    out = []
    for r in table or []:
        if isinstance(r, dict):
            m = _num(r.get("marginPct", r.get("margin_pct")))
            out.append([_num(r.get("min_score", r.get("minScore"))), _num(r["leverage"]),
                        m * 100 if m is not None and m <= 1 else m])
        elif isinstance(r, (list, tuple)):
            out.append([_num(r[0]), _num(r[1]), _num(r[2]) if len(r) > 2 else None])
    return sorted(out, key=lambda r: -r[0])


def score_rows(margin_key="marginPct", floor_key="minScore", below=None, rows=None, max_score=None):
    """Score tiers, highest first: a signal takes the first row its score reaches (leverageTiers by
    default, or `rows(inputs, ctx)` for a table kept elsewhere); a row without a margin uses
    `margin_key`. Scores between the entry floor and the lowest row take `below`, the scanner's
    fall-through leverage (a number or an input key). A row under the floor, or above `max_score`
    (the most the scanner's score can reach), never trades."""
    def size(rt, ctx):
        i = ctx["inputs"]
        floor = _num(i.get(floor_key)) if floor_key else None
        spans, top = [], None
        for lo, lev, m in _table_rows(rows(i, ctx) if rows else i.get("leverageTiers")):
            if max_score is None or lo <= max_score:
                spans.append([lo, top, _pct(m) if m is not None else _pct(i.get(margin_key)), lev])
                top = lo
        low = _num(i.get(below)) if isinstance(below, str) else below
        if low is not None and floor is not None and top is not None and floor < top:
            spans.append([floor, top, _pct(i.get(margin_key)), low])
        if floor is not None:
            spans = [[max(lo, floor), t, m, lev] for lo, t, m, lev in spans if t is None or t > floor]
        return _merge(spans, "score")
    return size


def code_rows(name, filename="scoring.py"):
    """score_rows' table from a list a scanner keeps in code (dog LEVERAGE_TIERS)."""
    return lambda i, ctx: code_constant(ctx["pkg_dir"], ctx["inst_dir"], filename, name)


def code_steps(ctx, func, filename="scoring.py"):
    """The (threshold, multiplier) ladder a sizing function keeps in code: `x >= N` branches that
    return or assign `base * M ...`, then the base for the rest (threshold None). Read with ast, never
    run, so a card follows its scanner; a function of any other shape stops the build."""
    path = os.path.join(ctx["pkg_dir"], ctx["inst_dir"], "scanners", filename)
    fn = next(n for n in ast.parse(open(path, encoding="utf-8").read()).body
              if isinstance(n, ast.FunctionDef) and n.name == func)

    def mult(stmt):
        node = stmt.value
        while isinstance(node, ast.BinOp) and isinstance(node.op, ast.Mult):
            for side in (node.right, node.left):
                if isinstance(side, ast.Constant) and isinstance(side.value, (int, float)):
                    return float(side.value)
            node = node.left
        return 1.0

    steps = []

    def walk(stmts):
        for st in stmts:
            if isinstance(st, ast.If):
                t = st.test
                if not (isinstance(t, ast.Compare) and len(t.ops) == 1 and isinstance(t.ops[0], ast.GtE)
                        and isinstance(t.comparators[0], ast.Constant)):
                    raise ValueError(f"{path}:{st.lineno}: {func} is not a ladder of `x >= N` steps")
                steps.append((t.comparators[0].value,
                              mult(next(b for b in st.body if isinstance(b, (ast.Return, ast.Assign))))))
                if st.orelse and walk(st.orelse):
                    return True
            elif isinstance(st, (ast.Return, ast.Assign)) and steps:
                steps.append((None, mult(st)))
                return True
        return False
    if not walk(fn.body):
        raise ValueError(f"{path}: {func} has no base case")
    return steps


def lev_clamp(key="leverageDefault", lo="leverageMin", hi="leverageMax", code=False):
    """One leverage: an input held to [lo, hi], input keys or (code=True) scan.py's _MIN/_MAX_LEVERAGE."""
    def lev(i, ctx):
        if code:
            lo_v, hi_v = (code_constant(ctx["pkg_dir"], ctx["inst_dir"], "scan.py", k)
                          for k in ("_MIN_LEVERAGE", "_MAX_LEVERAGE"))
        else:
            lo_v, hi_v = _num(i.get(lo)), _num(i.get(hi))
        v = int(_num(i.get(key)))
        return max(lo_v or 1, min(v, hi_v or v))
    return lev


def steps(func, base_key="marginPctBase", floor_key="minScore", lev=None, label="score", cap_key=None,
          regime_floor=None, note=None):
    """base_key x the multiplier of the highest step the score (or conviction) reaches, read from the
    scanner's own `func` (code_steps), capped at cap_key when above 0, times a regime intensity from
    `regime_floor` to 1 where the scanner scales by one. Steps under the entry floor never trade."""
    def size(rt, ctx):
        i = ctx["inputs"]
        base, cap = _pct(i.get(base_key)), ((_num(i.get(cap_key)) or None) if cap_key else None)
        floor = _num(i.get(floor_key)) if floor_key else None
        leverage = lev(i, ctx) if lev else flat_leverage(rt)
        spans, top = [], None
        for thr, m in code_steps(ctx, func):
            hi = _cap(round(base * m, 4), cap)
            lo = _cap(round(base * m * regime_floor, 4), cap) if regime_floor else hi
            spans.append([thr if thr is not None else floor, top, _span(lo, hi), leverage])
            top = thr if thr is not None else top
        if floor is not None:
            spans = [[max(a, floor) if a is not None else a, t, m, lev_] for a, t, m, lev_ in spans
                     if t is None or t > floor]
        out = _merge(spans, label)
        for c in out if note else ():
            c["note"] = note.format(**i)
        return out
    return size


def by_instance(**fns):
    """A package whose wallets run different engines (athena: a phalanx sleeve and an aegis sleeve)."""
    def size(rt, ctx):
        return fns[ctx["instance"]](rt, ctx)
    return size


def weights(base_key="marginPct", cap_key=None, lev_key="maxLeverage"):
    """base_key x the market's sizingWeights entry (bare ticker, else `_default`, else 1), the weight
    held to [0.1, 3.0] and the product capped at cap_key (scoring.sizing_weight): a case per size; the
    largest group is "every other market"."""
    def size(rt, ctx):
        i = ctx["inputs"]
        w = {_bare(k): v for k, v in (i.get("sizingWeights") or {}).items()}
        base, cap = _pct(i.get(base_key)), (_num(i.get(cap_key)) if cap_key else None)
        groups = {}
        for m in universe(rt) or []:
            wt = min(3.0, max(0.1, float(w.get(_bare(m), w.get("_DEFAULT", 1.0)))))
            groups.setdefault(_num(round(_cap(base * wt, cap), 4)), []).append(m)
        big = max(groups, key=lambda p: len(groups[p])) if len(groups) > 1 else None
        return [case("every other market", p, _num(i.get(lev_key))) if p == big and len(groups[p]) > 3
                else case(", ".join(ms), p, _num(i.get(lev_key)), markets=ms)
                for p, ms in sorted(groups.items(), key=lambda kv: -kv[0])]
    return size


def high_score(rt, ctx):
    # puffin / signals-hunter scan.py: highMarginPct when the trade score reaches highScoreThreshold,
    # else marginPct, at one leverage
    i = ctx["inputs"]
    thr, lev = _num(i.get("highScoreThreshold")), flat_leverage(rt)
    return [case(f"score {thr}+", _pct(i.get("highMarginPct")), lev),
            case(f"score {_num(i.get('minScore'))} to under {thr}", _pct(i.get("marginPct")), lev)]


def _burst(bump, floor):
    # hare / kite scoring.sizing: score 6 -> min(marginPct x 1.4, maxMarginPct) at maxLeverage; score 5
    # -> min(marginPct x 1.2, maxMarginPct) at min(stdLeverage + bump, maxLeverage); else marginPct at
    # stdLeverage. `floor`: the lowest score that trades (kite's entry needs a divergence, so 5).
    def size(rt, ctx):
        i = ctx["inputs"]
        base, cap = _pct(i.get("marginPct")), _num(i.get("maxMarginPct"))
        std, mx = _num(i.get("stdLeverage")), _num(i.get("maxLeverage"))
        out = [case("score 6", _cap(round(base * 1.4, 4), cap), mx),
               case("score 5", _cap(round(base * 1.2, 4), cap), min(std + bump, mx))]
        return out + ([case(f"score {floor}", base, std)] if floor < 5 else [])
    return size


def _python(rt, ctx):
    # python scoring.py: LEVERAGE_TIERS by score; get_margin_pct gives MARGIN_PCT_APEX at score 12+,
    # MARGIN_PCT_STRONG at 10+, else MARGIN_PCT_BASE; minScore is the floor
    k = lambda n: code_constant(ctx["pkg_dir"], ctx["inst_dir"], "scoring.py", n)
    margin = {12: k("MARGIN_PCT_APEX"), 10: k("MARGIN_PCT_STRONG")}
    rows = [[t["min_score"], t["leverage"], margin.get(t["min_score"], k("MARGIN_PCT_BASE"))]
            for t in k("LEVERAGE_TIERS")]
    return score_rows(rows=lambda i, c: rows)(rt, ctx)


def _relativity(rt, ctx):
    # relativity-xyz scoring.py: LEVERAGE_BASE, LEVERAGE_MID at LEVERAGE_MID_THRESHOLD+, LEVERAGE_HIGH at
    # LEVERAGE_HIGH_THRESHOLD+, capped at maxLeverage; its score tops out at 9, so the high tier never
    # trades. (The leverageTierBase/Mid/High inputs are never read.)
    k = lambda n: code_constant(ctx["pkg_dir"], ctx["inst_dir"], "scoring.py", n)
    i = ctx["inputs"]
    rows = [[k("LEVERAGE_HIGH_THRESHOLD"), k("LEVERAGE_HIGH")], [k("LEVERAGE_MID_THRESHOLD"), k("LEVERAGE_MID")],
            [_num(i.get("minScore")), k("LEVERAGE_BASE")]]
    rows = [[s, _cap(lev, _num(i.get("maxLeverage")))] for s, lev in rows]
    return score_rows(rows=lambda i_, c: rows, max_score=9)(rt, ctx)


def _whalehunter(rt, ctx):
    # scan.py: score = 4 + 1 when the smart side is at least 85% one-sided + 1 when the crowd leans the
    # other way; margin = min(marginPct x min(maxConvictionScale, 1 + 0.25 x (score - 4)), maxMarginPct)
    # at min(stdLeverage, maxLeverage)
    i = ctx["inputs"]
    base, cap, smax = _pct(i.get("marginPct")), _num(i.get("maxMarginPct", 25)), _num(i.get("maxConvictionScale", 2))
    lev = min(_num(i.get("stdLeverage", 3)), _num(i.get("maxLeverage", 5)))
    when = {6: "smart side 85%+ one-sided and the crowd leaning the other way",
            5: "one of those two", 4: "neither"}
    return [case(when[sc], _num(round(min(base * min(smax, 1 + 0.25 * (sc - 4)), cap), 4)), lev)
            for sc in (6, 5, 4)]


def _mandate(rt, ctx):
    # scoring.alloc_pct: baseAllocationPct + (maxAllocationPct - base) x clamp((score - goodScore) / 2,
    # 0, 1), at least minAllocationPct; its score tops out at 8 (4h and 1d bullish, 4h strength 0.8+)
    i = ctx["inputs"]
    base, cap, good = (_num(i.get(k)) for k in ("baseAllocationPct", "maxAllocationPct", "goodScore"))
    top = _num(round(min(base + (cap - base) * max(0.0, min(1.0, (8 - good) / 2)), cap), 4))
    return [case("score 8", top, flat_leverage(rt)), case(f"score {good} or less", base, flat_leverage(rt))]


VOL = "sized from the market's volatility (calmer markets larger)"


def _vol(i):
    """A vol-parity size, held to [minMarginPct, maxMarginPct] (fractions of 1 in these configs)."""
    return _span(round(i["minMarginPct"] * 100, 4), round(i["maxMarginPct"] * 100, 4))


def _caribou(rt, ctx):
    # scoring.vol_parity_margin_pct: baseRiskPct x referenceVolPct / the market's ATR %, held to
    # [minMarginPct, maxMarginPct]; scan.py: maxLeverage at score apexScore+, baseLeverage below
    i = ctx["inputs"]
    apex = _num(i["apexScore"])
    return [case(f"score {apex}+; {VOL}", _vol(i), _num(i["maxLeverage"])),
            case(f"score {_num(i['minScore'])} to under {apex}; {VOL}", _vol(i), _num(i["baseLeverage"]))]


def _hydra_hedge(rt, ctx):
    # hedge scan.py: hedgeRiskPct x referenceVolPct / the market's ATR % x a stress multiplier, held to
    # [minMarginPct, maxMarginPct], at inputs.leverage
    i = ctx["inputs"]
    return [case(f"every short; {VOL}", _vol(i), _num(i.get("leverage")))]


def _clips(rt, ctx):
    # dugong / manatee scan.py: every new position is marginPct, every add addMarginPct, at leverage
    i = ctx["inputs"]
    return [case("each new position", _pct(i.get("marginPct")), flat_leverage(rt)),
            case("each add to a held position", _pct(i.get("addMarginPct")), flat_leverage(rt))]


def _preipo(rt, ctx):
    # cub/preipo scan.py: marginPct x the name's weight (1 by default) x freshListing.starterSizeFactor
    # for a starter entry on a listing too new for the 4h read
    i = ctx["inputs"]
    base, lev = _pct(i.get("marginPct")), _num(i.get("maxLeverage"))
    factor = _num((i.get("freshListing") or {}).get("starterSizeFactor"))
    return [case("a confirmed entry", base, lev),
            case("a starter entry on a fresh listing", _num(round(base * factor, 4)), lev)]


def _squid(rt, ctx):
    # squid scoring.py: min(marginPct, maxMarginPct); leverage follows the mirrored traders' own, held to
    # [1, maxLeverage], stdLeverage when theirs is unknown
    i = ctx["inputs"]
    return [case(f"every entry; leverage follows the traders it mirrors ({_num(i.get('stdLeverage'))}x when unknown)",
                 _cap(_pct(i.get("marginPct")), _num(i.get("maxMarginPct"))), [1, _num(i.get("maxLeverage"))])]


def _dragonfly(rt, ctx):
    # dragonfly scoring.py: margin = max(band tier x the UTC session factor, 5) and leverage = the band's
    # tier, weekend-capped at weekendLeverageCap. get_session_factor: 0.6 on weekends; weekdays multiply
    # windows (Mon 0-8h x1.2, Thu 10-18h x1.3, Fri 14-20h x0.8, 14-17h x1.15) held to [0.5, 1.5], so
    # 0.8 to 1.495 on weekdays.
    i = ctx["inputs"]
    mt, lt, cap = i["marginPctTiers"], i["leverageTiers"], _num(i.get("weekendLeverageCap"))
    out = []
    for band in mt:
        m = _span(max(round(mt[band] * 0.6, 2), 5.0), max(round(mt[band] * 1.495, 2), 5.0))
        out.append(case(f"{band}-band signals; size moves with the UTC session", m,
                        _span(min(lt[band], cap) if cap else lt[band], lt[band])))
    return out


def _mantis(rt, ctx):
    # scoring.py: the first sizingTiers row the laggard's confidence reaches (minConfidence filters the
    # rest), its margin_pct at its leverage capped at maxLeverage.
    i = ctx["inputs"]
    rows = sorted(i.get("sizingTiers") or [], key=lambda t: -_num(t["confidence_min"]))
    out = []
    for n, t in enumerate(rows):
        lo = _num(t["confidence_min"])
        when = f"confidence {lo}+" if not n else f"confidence {lo} to under {_num(rows[n - 1]['confidence_min'])}"
        out.append(case(when, _pct(t["margin_pct"]), _cap(_num(t["leverage"]), _num(i.get("maxLeverage")))))
    return out


def _ox(rt, ctx):
    # scan.py / scoring.py: a sleeve's margin is min(portfolioBudgetPct x its inverse-volatility weight,
    # maxWeightPct) of the account, emitted as that percent unconverted, so the runtime applies it to free
    # margin; ballast multiplies the budget by riskOffMultiplier when its risk-off lean is on.
    i = ctx["inputs"]
    budget, cap = _num(i["portfolioBudgetPct"] * 100), _num(i["maxWeightPct"] * 100)
    text = (f"each sleeve's volatility: {budget}% of the account split across the sleeves by inverse "
            f"volatility, at most {cap}% per sleeve")
    if _num(i.get("riskOffMultiplier")):
        text += f" ({_num(budget * i['riskOffMultiplier'])}% in all while its risk-off lean is on)"
    return [case("every sleeve", None, _num(i.get("maxLeverage")), set_by=text)]


def atr_leverage(rt, ctx):
    # ibex / moose scoring.leverage_for: the largest whole leverage at which the stop (stopRoePct) sits
    # atrStopMultiple ATRs from entry, held to [leverageMin, leverageMax]: a calmer coin, more leverage
    i = ctx["inputs"]
    return [case("every entry; leverage set per coin from its volatility (calmer coins higher)",
                 flat_margin(rt), _span(i.get("leverageMin"), i.get("leverageMax")))]


def _kudu(rt, ctx):
    # scan.py `legs`: a basket name is marginPct of the ACCOUNT at basketLeverage, the washout leg is
    # washoutMarginPct at washoutLeverage (clip = account_value * pct / 100, emitted as % of free margin).
    i = ctx["inputs"]
    return [case("each basket name", _pct(i.get("marginPct")), _num(i.get("basketLeverage")), ACCOUNT),
            case(f"the washout leg ({i.get('washoutAsset')}, bought after a washout)",
                 _pct(i.get("washoutMarginPct")), _num(i.get("washoutLeverage")), ACCOUNT)]


def _ibis(trend_base, range_base):
    # ibis scan.py: a TREND thesis at leverageTrend from trend_base, a RANGE thesis at leverageRange from
    # range_base, each held to [leverageMin, leverageMax] and stepped by scoring.margin_tier_pct
    def size(rt, ctx):
        out = []
        for regime, base, lev_key in (("trend", trend_base, "leverageTrend"), ("range", range_base, "leverageRange")):
            for c in steps("margin_tier_pct", base_key=base, lev=lev_clamp(lev_key))(rt, ctx):
                c["when"] = f"{regime} regime, {c['when']}"
                out.append(c)
        return out
    return size


