def max_positions(rt):
    """The runtime's `slots`, lowered by a scanner cap and by a static universe (the runtime holds one
    position per market per wallet, so nine markets never fill ten slots)."""
    inp = _scanner_inputs(rt)
    vals = [_num((rt.get("strategy") or {}).get("slots")), _num(inp.get("maxSlots")),
            _num(inp.get("maxPositions")), len(universe(rt) or []) or None]
    vals = [v for v in vals if v]
    return min(vals) if vals else None


def exits(rt):
    dp = ((rt.get("exit") or {}).get("dsl_preset")) or {}
    out = {"stop_loss_roe_pct": _num((dp.get("phase1") or {}).get("max_loss_pct")),
           "profit_locks": [{"at_roe_pct": _num(t.get("trigger_pct")),
                             "keeps_pct_of_peak_gain": _num(t.get("lock_hw_pct"))}
                            for t in ((dp.get("phase2") or {}).get("tiers") or []) if isinstance(t, dict)]}
    clocks = {}
    ht, wp, dw = (dp.get(k) or {} for k in ("hard_timeout", "weak_peak_cut", "dead_weight_cut"))
    if ht.get("enabled"):
        clocks["closes_after_min"] = _num(ht.get("interval_in_minutes"))
    if dw.get("enabled"):
        clocks["closes_if_underwater_for_min"] = _num(dw.get("interval_in_minutes"))
    if wp.get("enabled"):
        clocks["closes_faded_gain_after_min"] = _num(wp.get("interval_in_minutes"))
        clocks["faded_gain_below_roe_pct"] = _num(wp.get("min_value"))
    if clocks:
        out["time_exits"] = clocks
    if any(a.get("action_type") == "CLOSE_POSITION" for a in rt.get("actions") or [] if isinstance(a, dict)):
        out["closes_on_signal"] = True
    return out


def cadence_seconds(rt):
    vals = [_num(s.get("interval_seconds")) for s in rt.get("scanners") or []
            if isinstance(s, dict) and s.get("type") == "external_scanner"]
    vals = [v for v in vals if v]
    return min(vals) if vals else None


def universe(rt):
    """The fixed list of markets a scanner trades, when it has one (a live-board scanner has none)."""
    inp = _scanner_inputs(rt)
    for key in ("allowedAssets", "universe", "sleeves"):
        aa = inp.get(key)
        if isinstance(aa, list) and aa and all(isinstance(a, str) for a in aa):
            return list(aa)
    baskets = [a for k in ("longBasket", "shortBasket") for a in inp.get(k) or [] if isinstance(a, str)]
    if baskets:
        return baskets
    if isinstance(inp.get("asset"), str):
        return [inp["asset"]]
    return None


def _collapse(cases):
    """Cases that size every signal alike are one case, "every entry" (a tier table flattened to one
    value, or one score row that is also the entry floor)."""
    if len({(str(c["margin_pct"]), c["of"], str(c["leverage"]), c.get("set_by")) for c in cases}) > 1:
        return cases
    keep = {k: v for k, v in cases[0].items() if k in ("set_by", "note")}  # note: hoisted to the wallet
    return [case("every entry", cases[0]["margin_pct"], cases[0]["leverage"], cases[0]["of"], **keep)]


def wallet_defaults(sid, inst, rt, pkg_dir):
    ctx = {"inputs": _scanner_inputs(rt), "strategy": rt.get("strategy") or {}, "pkg_dir": pkg_dir,
           "inst_dir": os.path.dirname(inst.get("runtime") or ""), "instance": inst.get("name")}
    out = {"wallet": inst.get("name"),
           "funding_share": _num(inst.get("funding_share")) or 1,
           "max_positions": max_positions(rt),
           "size": _collapse(SIZING.get(sid, default_size)(rt, ctx))}
    notes = {c.pop("note") for c in out["size"] if "note" in c}
    if notes:
        out["size_note"] = "; ".join(sorted(notes))
    out.update(exits(rt))
    out["cadence_seconds"] = cadence_seconds(rt)
    u = universe(rt)
    if u:
        out["universe"] = u
    return out


def record_defaults(sid, manifest, runtimes, pkg_dir):
    """`defaults` for one catalog record: one entry per wallet, in manifest order."""
    return {"wallets": [wallet_defaults(sid, inst, runtimes.get(inst.get("name")) or {}, pkg_dir)
                        for inst in manifest.get("instances") or []]}
